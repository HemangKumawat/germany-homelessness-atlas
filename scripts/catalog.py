#!/usr/bin/env python3
"""Write data/CATALOG.md and data/catalog/sources.csv from data/atlas.db (read-only).

The catalog is the machine-readable index of every registered source: URL, publisher, licence,
retrieval date and sha256 of the archived copy, plus row counts per table and per domain.
It contains metadata only, never document text.

    python3 scripts/catalog.py            # uses data/atlas.db
    python3 scripts/catalog.py --db X.db
"""
from __future__ import annotations

import argparse
import csv
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CORE = ["source", "org", "org_person", "award", "metric", "zaehlung", "facility", "law", "media", "doc",
        "places", "geo_kreis", "geo_gemeinde"]
CSV_COLS = ["id", "domain", "url", "title", "publisher", "license", "license_url", "attribution",
            "retrieved_at", "sha256", "content_type", "redistribute_fulltext"]


def cell(v, n=160) -> str:
    s = " ".join(str(v or "").split()).replace("|", "\\|")
    return s if len(s) <= n else s[: n - 1] + "…"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=str(ROOT / "data" / "atlas.db"))
    a = ap.parse_args()
    c = sqlite3.connect(f"file:{a.db}?mode=ro", uri=True)
    c.row_factory = sqlite3.Row
    tables = {r[0] for r in c.execute("SELECT name FROM sqlite_master WHERE type='table'")}
    out = ROOT / "data" / "catalog"
    out.mkdir(parents=True, exist_ok=True)

    with open(out / "sources.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(CSV_COLS)
        for r in c.execute(f"SELECT {', '.join(CSV_COLS)} FROM source ORDER BY id"):
            w.writerow([r[k] for k in CSV_COLS])

    L = ["# Data catalog", "",
         "Generated by `python3 scripts/catalog.py` from `data/atlas.db`. Do not edit by hand.",
         "Every row in the atlas carries a `source_id` that points at one `source` row listed in",
         "[`catalog/sources.csv`](catalog/sources.csv) (URL, publisher, licence, retrieval date, sha256 of the archived copy).",
         "Human-written notes on each source and its terms are in [`../docs/SOURCES.md`](../docs/SOURCES.md).", "",
         "## Rows per table", "", "| table | rows |", "|---|---:|"]
    for t in CORE:
        if t in tables:
            L.append(f"| `{t}` | {c.execute(f'SELECT count(*) FROM {t}').fetchone()[0]:,} |")
    L += ["", "## Sources per ingest domain", "", "| domain | sources | publishers |", "|---|---:|---:|"]
    for r in c.execute("SELECT domain, count(*) n, count(DISTINCT publisher) p FROM source GROUP BY 1 ORDER BY 2 DESC"):
        L.append(f"| `{r['domain']}` | {r['n']:,} | {r['p']:,} |")
    L += ["", "## Datasets (domain × publisher × licence)", "",
          "One line per publisher and licence statement. `fulltext` = 1 means the licence allows redistributing the",
          "document text; 0 means only facts, metadata and short quotes are used.", "",
          "| domain | publisher | licence / terms | sources | fulltext | example URL |", "|---|---|---|---:|:-:|---|"]
    q = """SELECT domain, publisher, license, count(*) n, max(coalesce(redistribute_fulltext,0)) ft, min(url) u
           FROM source GROUP BY domain, publisher, license ORDER BY domain, n DESC"""
    for r in c.execute(q):
        L.append(f"| `{r['domain']}` | {cell(r['publisher'], 80)} | {cell(r['license'])} | {r['n']:,} | {r['ft']} | {cell(r['u'], 120)} |")
    (ROOT / "data" / "CATALOG.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"data/CATALOG.md, data/catalog/sources.csv: {c.execute('SELECT count(*) FROM source').fetchone()[0]} sources")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
